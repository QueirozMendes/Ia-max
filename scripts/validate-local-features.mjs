import {mkdir,writeFile,readFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {proposeLocally} from '../lib/local-developer.js';
import {applyInWorktree,checkSyntax,reviewWorktree} from '../lib/project-worktree.js';
import {runProjectTests} from '../lib/project-tests.js';
import {runCodex,replicaPrompt} from '../lib/codex-agent.js';
import {rankNotes,suggestLinks} from '../lib/neural.js';
import {createMemoryStore} from '../lib/memory.js';
import {chooseBrain} from '../lib/brain-router.js';
import assert from 'node:assert/strict';
const base=resolve('.runtime/validation-'+Date.now());
await mkdir(base,{recursive:true});
const report={directory:base};
try{
 const store=createMemoryStore(join(base,'memory'));
 await store.save('Teste fictício: estudar JavaScript.',null);
 assert.match((await store.read()).memory,/JavaScript/);report.memoryPersistence=true;
 const notes=[{id:'a',title:'JavaScript testes',body:'Estudar testes JavaScript',links:[],useInChat:true,area:'projetos'},{id:'b',title:'Estudar JavaScript',body:'JavaScript e testes locais',links:[],useInChat:true,area:'aprendizado'}];
 assert.ok(rankNotes(notes,'JavaScript').length===2);assert.ok(suggestLinks(notes).length);report.neuralRetrievalAndLinks=true;
 assert.equal(chooseBrain({mode:'auto',requested:'local'}).provider,'ollama');assert.ok(chooseBrain({mode:'auto',requested:'openai',allowCloud:false}).error);report.multiBrainNoCloudFallback=true;
 const fixture=join(base,'fixture');await mkdir(join(fixture,'test'),{recursive:true});
 const text='export const sum = (a,b) => a-b;\n';
 await writeFile(join(fixture,'math.js'),text);
 await writeFile(join(fixture,'package.json'),JSON.stringify({name:'max-validation',private:true,type:'module'}));
 await writeFile(join(fixture,'test/math.test.js'),"import test from 'node:test';import assert from 'node:assert/strict';import {sum} from '../math.js';test('addition',()=>assert.equal(sum(2,3),5));\n");
 const git=args=>execFileSync('git',args,{cwd:fixture,windowsHide:true,encoding:'utf8'});
 git(['init']);git(['add','.']);git(['-c','user.name=Max Validation','-c','user.email=max-validation@localhost','commit','-m','Synthetic validation fixture']);
 const files=[{path:'math.js',text,sha256:createHash('sha256').update(text).digest('hex')}];
 const proposal=await proposeLocally({task:'Corrija sum para somar a e b. Não altere a estrutura.',files});
 assert.ok(proposal.changes.length);report.localDeveloperProposal=proposal.summary;
 const applied=await applyInWorktree({root:fixture,workspace:join(base,'copies'),proposal,approved:()=>true});report.isolatedBranch=applied.branch;
 const syntax=await checkSyntax(applied.directory,['math.js'],()=>true);assert.ok(syntax.every(r=>r.ok));
 const test=await runProjectTests({directory:applied.directory,paths:['test/math.test.js']});assert.equal(test.ok,true);report.localDeveloperTests=test.output;
 assert.match(replicaPrompt('/replica-test validate addition'),/Replica/);report.replicaPack=true;
 const config=JSON.parse(await readFile('.runtime/integrations.json','utf8'));
 const codex=await runCodex({directory:applied.directory,binary:config.codexBinary,task:'Validação sintética. Leia math.js e test/math.test.js. Execute node --test test/math.test.js. Não altere arquivos. Responda apenas se passou.'});
 report.codex={ok:codex.ok,output:codex.output};report.review=await reviewWorktree(applied.directory);
 report.ok=codex.ok;
}catch(error){report.ok=false;report.error=error.stack;}
await writeFile(join(base,'result.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
if(!report.ok)process.exitCode=1;
